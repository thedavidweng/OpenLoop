export function iconSvg(name: string): string {
  const body = PATHS[name] ?? "";
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

export function setIcon(element: Element, name: string): void {
  element.setAttribute("data-icon", name);
  element.innerHTML = iconSvg(name);
}

export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll("i[data-icon]").forEach((element) => {
    if (!element.firstChild) {
      element.innerHTML = iconSvg(element.getAttribute("data-icon") ?? "");
    }
  });
}
